/**
 * Lists what is still a placeholder in the seed files, for the content tracking issue (#14).
 * Pure functions: the script in scripts/content-status.ts reads the files and prints the report.
 */

export type SeedDoc = Record<string, unknown>

export type FileStatus = {
  file: string
  total: number
  /** Placeholders grouped by their note, in the order the notes first appear. */
  missing: { note: string; items: string[] }[]
}

const text = (value: unknown) => (typeof value === 'string' && value.trim() ? value : undefined)

/** A short, human name for one seed document, e.g. "Vice President" or "Trade Fair (health-week-2026-day-2)". */
export function labelFor(doc: SeedDoc, index: number): string {
  const title = text(doc.title)
  const slug = text(doc.slug)
  return (
    text(doc.office) ??
    text(doc.position) ??
    (title && slug ? `${title} (${slug})` : undefined) ??
    title ??
    text(doc.name) ??
    slug ??
    text(doc.key) ??
    `item ${index + 1}`
  )
}

export function fileStatus(file: string, docs: SeedDoc[]): FileStatus {
  const groups = new Map<string, string[]>()
  docs.forEach((doc, i) => {
    if (doc.isPlaceholder !== true) return
    const note = text(doc.placeholderNote) ?? 'No note given'
    groups.set(note, [...(groups.get(note) ?? []), labelFor(doc, i)])
  })
  return {
    file,
    total: docs.length,
    missing: [...groups].map(([note, items]) => ({ note, items })),
  }
}

const count = (status: FileStatus) => status.missing.reduce((n, g) => n + g.items.length, 0)

/** Markdown report with a checkbox per missing piece, ready to paste into the tracking issue. */
export function formatReport(statuses: FileStatus[]): string {
  const total = statuses.reduce((n, s) => n + s.total, 0)
  const placeholders = statuses.reduce((n, s) => n + count(s), 0)
  const lines = [
    '## Content still missing',
    '',
    `${placeholders} of ${total} seeded items are placeholders. Generated by \`npm run content:status -w server\`.`,
  ]
  for (const s of statuses) {
    lines.push(
      '',
      `### ${s.file}: ${count(s) === 0 ? 'complete' : `${count(s)} of ${s.total} placeholders`}`,
    )
    for (const g of s.missing)
      lines.push(`- [ ] ${g.note} (${g.items.length}): ${g.items.join(', ')}`)
  }
  return lines.join('\n') + '\n'
}
